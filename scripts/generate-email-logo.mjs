/**
 * Rebuilds src/lib/email/logo-asset.ts and public/email-logo.png from the
 * repository's own logo.
 *
 * The artwork is used exactly as published: colours, transparency and aspect
 * ratio are preserved, so the only operations here are a lossless downscale to
 * twice the size the email renders it at (for Retina screens) and PNG
 * optimisation. Run with: node scripts/generate-email-logo.mjs
 */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'public', 'logo.png');
const TARGET = join(ROOT, 'src', 'lib', 'email', 'logo-asset.ts');
const PUBLIC_COPY = join(ROOT, 'public', 'email-logo.png');

/** Width the logo is drawn at in the email; the asset ships at 2x for sharpness. */
const RENDER_WIDTH = 200;
const RETINA_SCALE = 2;

const CONTENT_ID = 'vpd-logo';
const FILENAME = 'vpd-logo.png';

const source = sharp(SOURCE, { failOn: 'none' });
const original = await source.metadata();

const optimised = await source
  .resize({
    width: RENDER_WIDTH * RETINA_SCALE,
    fit: 'contain',
    withoutEnlargement: true,
  })
  .png({ compressionLevel: 9, effort: 10, adaptiveFiltering: true })
  .toBuffer();

const output = await sharp(optimised).metadata();
const base64 = optimised.toString('base64');

const module = `/**
 * Generated by scripts/generate-email-logo.mjs from public/logo.png — do not edit
 * by hand. The bytes are the published logo, downscaled with colours, alpha and
 * aspect ratio untouched (${original.width}x${original.height} -> ${output.width}x${output.height}).
 *
 * Emails reference the logo by HTTPS URL and keep this copy as an inline cid
 * attachment, so the header still renders in clients that block remote images.
 */
export const LOGO_BASE64 =
  '${base64}';

export const LOGO_CONTENT_ID = '${CONTENT_ID}';
export const LOGO_FILENAME = '${FILENAME}';
export const LOGO_MIME_TYPE = 'image/png';

/** Drawn at this size; the asset itself is ${RETINA_SCALE}x for crisp Retina rendering. */
export const LOGO_RENDER_WIDTH = ${RENDER_WIDTH};
export const LOGO_RENDER_HEIGHT = ${Math.round((output.height / output.width) * RENDER_WIDTH)};
`;

writeFileSync(TARGET, module, 'utf8');
writeFileSync(PUBLIC_COPY, optimised);

console.log(
  `${original.width}x${original.height} -> ${output.width}x${output.height}, ` +
    `${(optimised.length / 1024).toFixed(1)} KB, renders at ` +
    `${RENDER_WIDTH}x${Math.round((output.height / output.width) * RENDER_WIDTH)} ` +
    `(logo-asset.ts + public/email-logo.png)`
);
